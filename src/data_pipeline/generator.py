def generate_dataset(seed: int = RANDOM_SEED) -> pd.DataFrame:
    """
    Generate a reproducible synthetic CloudTrail-style dataset (v2).

    Parameters
    ----------
    seed : int
        Random seed for full reproducibility. Default is 42.

    Returns
    -------
    pd.DataFrame
        5,000 rows × 13 columns:
        event_id, event_time, event_source, event_name, source_ip,
        user_identity, aws_region, error_code, failed_attempts,
        unusual_location, privilege_change, label, data_source.
    """
    rng = random.Random(seed)
    fake = Faker()
    Faker.seed(seed)

    normal_records = [_generate_normal(rng, fake) for _ in range(N_NORMAL)]

    suspicious_records = (
        _scenario_brute_force(rng, fake)
        + _scenario_privilege_escalation(rng, fake)
        + _scenario_audit_delete(rng, fake)
        + _scenario_s3_exfiltration(rng, fake)
        + _scenario_sts_abuse(rng, fake)
    )

    all_records = normal_records + suspicious_records
    rng.shuffle(all_records)

    df = pd.DataFrame(all_records)

    df = df[[
        "event_id", "event_time", "event_source", "event_name",
        "source_ip", "user_identity", "aws_region", "error_code",
        "failed_attempts", "unusual_location", "privilege_change",
        "label", "data_source",
    ]]

    return df


def save_raw_csv(df: pd.DataFrame, path: str) -> None:
    """Save the raw generated DataFrame to a CSV file."""
    df.to_csv(path, index=False)
    print(f"[generator] Saved {len(df):,} records to {path}")
    print(
        f"[generator] Label distribution:\n"
        f"  Normal (0):     {(df['label'] == 0).sum():,}\n"
        f"  Suspicious (1): {(df['label'] == 1).sum():,}"
    )
    print(
        "[generator] SYNTHETIC DATA NOTICE: This dataset is entirely "
        "synthetic. It does not represent real AWS activity and cannot "
        "establish real-world detection performance."
    )


