"""
generator.py
============
Synthetic AWS CloudTrail-style log generator.

VERSION: v2 — noise-injected (Option B)
PREVIOUS: v1 original backed up at data/raw/cloudtrail_synthetic_v1_original.csv

IMPORTANT — SYNTHETIC DATA NOTICE
==================================
This file produces ENTIRELY SYNTHETIC data for development and testing.
No real AWS credentials, real user identities, or real IP addresses are used.
All IP addresses are drawn from IANA-reserved documentation ranges (RFC 5737)
that cannot route on the public internet.

Class labels are assigned by SCENARIO MEMBERSHIP — a record is suspicious
because it was generated by an attack scenario function, NOT because any
individual risk flag is set. Risk flags (unusual_location, is_error, etc.)
are set probabilistically within each scenario to produce realistic overlap.

Even with noise injection, performance metrics on this dataset do NOT
establish real-world cloud security detection performance. They only reflect
how well the model learns the synthetic patterns.

Reproducing the dataset:
    The generator uses a fixed seed (default 42) so the exact same 5,000-record
    dataset is produced every time generate_dataset(seed=42) is called.

Dataset composition:
    4,000 normal records  (label = 0)
    1,000 suspicious records across 5 attack scenarios (label = 1)
        - 200 brute-force login attempts
        - 200 privilege escalation events
        - 200 audit-trail deletion / disable events
        - 200 unusual S3 data-access events
        - 200 unusual STS credential events

Noise rates in NORMAL records (v2):
    ~8%  have an occasional error (is_error=1)
    ~5%  have unusual_location=1  (travelling user / VPN)
    ~4%  are legitimate admin actions (may set privilege_change=1)
    ~20% occur outside business hours (timezone / late workers)

Relaxed suspicious-record rates (v2):
    Brute-force:          unusual_location=1  90% (was 100%)
    Privilege escalation: unusual_location=1  80% (was 100%)
    S3 exfiltration:      unusual_location=1  85% (was 100%)
    STS abuse:            unusual_location=1  85% (was 100%)
    Audit delete:         unchanged (~80%)

Data leakage prevention:
    - 'label' is assigned by scenario membership; it is the TARGET variable
      only and is never used as a model input.
    - 'failed_attempts' in the raw data is stored by the generator.
      The feature engineering step RE-DERIVES it from the event log
      (rolling per-user AccessDenied count), so no look-ahead leakage occurs.
    - No generator metadata (scenario name, internal flags) is written to
      any output column.
"""

import uuid
import random
from datetime import datetime, timezone, timedelta

import pandas as pd
from faker import Faker

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

RANDOM_SEED = 42
TOTAL_RECORDS = 5000
N_NORMAL = 4000
N_SUSPICIOUS = 1000
N_PER_SCENARIO = 200       # 5 scenarios × 200 = 1,000

# IANA RFC 5737 documentation-only IP ranges — never publicly routable
NORMAL_IP_PREFIXES = ["192.0.2.", "198.51.100."]      # "known office" IPs
UNUSUAL_IP_PREFIXES = ["203.0.113."]                   # "external" IPs

# Normal day-to-day API calls
NORMAL_ACTIONS = {
    "s3.amazonaws.com": [
        "GetObject", "PutObject", "ListBuckets", "HeadObject",
    ],
    "ec2.amazonaws.com": [
        "DescribeInstances", "DescribeSecurityGroups",
        "StartInstances", "StopInstances",
    ],
    "iam.amazonaws.com": [
        "GetUser", "ListUsers", "ListRoles", "GetPolicy",
    ],
    "sts.amazonaws.com": [
        "GetCallerIdentity", "AssumeRole",
    ],
    "kms.amazonaws.com": [
        "DescribeKey", "ListKeys", "GenerateDataKey",
    ],
    "cloudtrail.amazonaws.com": [
        "DescribeTrails", "GetTrailStatus", "LookupEvents",
    ],
}

# Legitimate admin actions that happen to be 'high-risk' by name.
# Used for the ~4% normal-record admin noise so that is_high_risk_action
# appears in BOTH classes and is not a perfect predictor.
NORMAL_ADMIN_ACTIONS = [
    "CreateUser",           # admin creating a new employee account
    "AttachUserPolicy",     # admin granting S3 read to a developer
    "AddUserToGroup",       # admin adding user to an existing group
    "AssumeRole",           # admin using a cross-account role
    "GetFederationToken",   # admin setting up federated access
]

# Attack-scenario specific action lists
PRIVILEGE_ACTIONS = [
    "CreateUser", "AttachUserPolicy", "PutRolePolicy",
    "AddUserToGroup", "UpdateAssumeRolePolicy",
]
AUDIT_DELETE_ACTIONS = [
    "DeleteTrail", "StopLogging", "UpdateTrail",
]
S3_EXFIL_ACTIONS = [
    "GetObject", "ListBuckets", "GetBucketAcl",
    "PutBucketAcl", "DeleteBucket",
]
STS_ABUSE_ACTIONS = [
    "AssumeRole", "AssumeRoleWithWebIdentity",
    "GetFederationToken", "GetSessionToken",
]

AWS_REGIONS = [
    "us-east-1", "us-west-2", "eu-west-1",
    "ap-southeast-1", "ap-northeast-1",
]

# Actions that set privilege_change = 1 (used by both generator and features.py)
PRIVILEGE_CHANGE_ACTIONS = {
    "CreateUser", "AttachUserPolicy", "PutRolePolicy",
    "AddUserToGroup", "UpdateAssumeRolePolicy",
    "DeleteUser", "DetachUserPolicy", "RemoveUserFromGroup",
}

# Normal working hours (UTC)
BUSINESS_HOUR_START = 8
BUSINESS_HOUR_END = 18

# ---------------------------------------------------------------------------
# Noise rates for normal records (v2)
# These are probabilities, not exact counts.
# Exact observed rates will vary slightly with different seeds.
# ---------------------------------------------------------------------------
NORMAL_ERROR_RATE = 0.08          # ~8%  occasional AccessDenied
NORMAL_UNUSUAL_LOCATION_RATE = 0.05   # ~5%  travelling / VPN
NORMAL_ADMIN_ACTION_RATE = 0.04   # ~4%  legitimate admin IAM action
NORMAL_OFF_HOURS_RATE = 0.20      # ~20% timezone / late worker


# ---------------------------------------------------------------------------
# Helper functions
# ---------------------------------------------------------------------------

def _make_ip(rng: random.Random, unusual: bool) -> str:
    """Return a documentation-range IP address (RFC 5737)."""
    prefixes = UNUSUAL_IP_PREFIXES if unusual else NORMAL_IP_PREFIXES
    prefix = rng.choice(prefixes)
    return f"{prefix}{rng.randint(1, 254)}"


def _make_timestamp(
    rng: random.Random,
    unusual_hour: bool = False,
    any_hour: bool = False,
) -> str:
    """
    Return an ISO 8601 UTC timestamp string.

    Parameters
    ----------
    unusual_hour : bool
        If True, pick an hour in 0–5 (attack off-hours pattern).
    any_hour : bool
        If True, pick any hour 0–23 (realistic normal off-hours workers).
        Overrides unusual_hour when both are True.
    """
    base = datetime(2024, 1, 1, tzinfo=timezone.utc)
    days_offset = rng.randint(0, 179)   # spread across 180-day window

    if any_hour:
        hour = rng.randint(0, 23)
    elif unusual_hour:
        hour = rng.randint(0, 5)        # midnight – 5 AM (UTC)
    else:
        hour = rng.randint(BUSINESS_HOUR_START, BUSINESS_HOUR_END)

    minute = rng.randint(0, 59)
    second = rng.randint(0, 59)
    ts = base + timedelta(
        days=days_offset, hours=hour, minutes=minute, seconds=second
    )
    return ts.strftime("%Y-%m-%dT%H:%M:%SZ")


def _make_user(
    fake: Faker,
    rng: random.Random,
    is_root: bool = False,
    is_service: bool = False,
) -> str:
    """Return a fictional identity string (never a real person)."""
    if is_root:
        return "root"
    if is_service:
        return rng.choice([
            "svc-backup-role", "svc-deploy-role",
            "svc-monitoring-role", "svc-temp-role",
        ])
    first = fake.first_name().lower()
    return f"{first}@example-corp.com"


# ---------------------------------------------------------------------------
# Normal record generator (v2 — with noise)
# ---------------------------------------------------------------------------

def _generate_normal(rng: random.Random, fake: Faker) -> dict:
    """
    Generate one normal (label=0) CloudTrail-style record.

    v2 changes vs v1:
    - ~8%  chance of an AccessDenied error (realistic typo / expired token)
    - ~5%  chance of unusual_location=1 (travelling user / VPN)
    - ~4%  chance of a legitimate admin IAM action (introduces high-risk action
           and possibly privilege_change into the normal class)
    - ~20% chance of off-hours timestamp (timezone / late worker)

    The label is ALWAYS 0 for records created by this function.
    """
    # --- Decide noise flags independently ---
    has_error = rng.random() < NORMAL_ERROR_RATE
    has_unusual_location = rng.random() < NORMAL_UNUSUAL_LOCATION_RATE
    is_admin_action = rng.random() < NORMAL_ADMIN_ACTION_RATE
    is_off_hours = rng.random() < NORMAL_OFF_HOURS_RATE

    # --- Service and action ---
    if is_admin_action:
        service = "iam.amazonaws.com"
        action = rng.choice(NORMAL_ADMIN_ACTIONS)
    else:
        service = rng.choice(list(NORMAL_ACTIONS.keys()))
        action = rng.choice(NORMAL_ACTIONS[service])

    privilege_change = 1 if action in PRIVILEGE_CHANGE_ACTIONS else 0

    # --- Location and timestamp ---
    ip = _make_ip(rng, unusual=has_unusual_location)
    timestamp = _make_timestamp(rng, any_hour=is_off_hours)

    # --- Error and failure counts ---
    error_code = "AccessDenied" if has_error else ""
    # 1–2 failed attempts only when the record itself is an error
    failed_attempts = rng.randint(1, 2) if has_error else 0

    return {
        "event_id": str(uuid.UUID(int=rng.getrandbits(128))),
        "event_time": timestamp,
        "event_source": service,
        "event_name": action,
        "source_ip": ip,
        "user_identity": _make_user(fake, rng),
        "aws_region": rng.choice(AWS_REGIONS),
        "error_code": error_code,
        "failed_attempts": failed_attempts,
        "unusual_location": int(has_unusual_location),
        "privilege_change": privilege_change,
        "label": 0,                    # ALWAYS 0 — assigned by scenario
        "data_source": "synthetic",
    }


# ---------------------------------------------------------------------------
# Suspicious scenario generators (v2 — relaxed indicators)
# ---------------------------------------------------------------------------

def _scenario_brute_force(rng: random.Random, fake: Faker) -> list[dict]:
    """
    Scenario 1: Brute-force login attempts (label=1).

    v2 change: unusual_location=1 with 90% probability (was 100%).
    10% of attacks originate from a compromised internal / known IP.
    v2 change: AccessDenied with 85% probability (was 100%).
    15% of brute-force attempts eventually succeed in the log window.
    """
    records = []
    for _ in range(N_PER_SCENARIO):
        unusual = rng.random() < 0.90         # 90% unusual
        has_error = rng.random() < 0.85       # 85% AccessDenied

        records.append({
            "event_id": str(uuid.UUID(int=rng.getrandbits(128))),
            "event_time": _make_timestamp(rng, unusual_hour=True),
            "event_source": "iam.amazonaws.com",
            "event_name": rng.choice(["GetUser", "GetLoginProfile"]),
            "source_ip": _make_ip(rng, unusual=unusual),
            "user_identity": rng.choice([
                "admin@example-corp.com", "root", _make_user(fake, rng),
            ]),
            "aws_region": rng.choice(["ap-northeast-1", "eu-west-1"]),
            "error_code": "AccessDenied" if has_error else "",
            "failed_attempts": rng.randint(5, 15),
            "unusual_location": int(unusual),
            "privilege_change": 0,
            "label": 1,
            "data_source": "synthetic",
        })
    return records


